// Pulls the exact path data of the live `svg-animated-{octagon,prism,spark}` icons
// (static text extraction, no code execution) and writes js/data/animated-icons.js.
import fs from 'node:fs';

const src = fs.readFileSync('reference/code/50b053bcb0308ac4.pretty.js', 'utf8');
const block = (name) => {
  const i = src.indexOf(`"svg-animated-${name}"`);
  const end = src.indexOf('case "', i);
  return src.slice(i, end);
};
const paths = (txt) => [...txt.matchAll(/\bd: "([^"]+)"/g)].map((m) => m[1]);
const octagon = paths(block('octagon'));
const prism = paths(block('prism'));
const spark = src.match(/\bd = "(m39[^"]+)"/)[1];
if (octagon.length !== 3 || prism.length !== 2) throw new Error('unexpected icon structure');

const out = `// Generated by tools/extract-animated-icons.mjs from the live bundle — do not edit.
// Animated outline icons shown large behind the solution cards on hover (svg-animated-*).
// data-from = the Motion "hide" variant each path animates from.
export const ANIMATED_ICONS = {
  octagon: (sw) => \`<svg xmlns="http://www.w3.org/2000/svg" fill="none" viewBox="0 0 95 95" class="svg-animated-octagon"><path data-from='{"scale":0.625}' stroke="currentColor" stroke-width="\${sw}" d="${octagon[0]}"/><path data-from='{"scale":0.8125}' stroke="currentColor" stroke-width="\${sw}" d="${octagon[1]}"/><path stroke="currentColor" stroke-width="\${sw}" d="${octagon[2]}"/></svg>\`,
  prism: (sw) => \`<svg xmlns="http://www.w3.org/2000/svg" fill="none" viewBox="0 0 80 96" class="svg-animated-prism"><path data-from='{"scaleX":0.5}' stroke="currentColor" stroke-miterlimit="10" stroke-width="\${sw}" d="${prism[0]}"/><path data-from='{"scaleX":0.5}' stroke="currentColor" stroke-miterlimit="10" stroke-width="\${sw}" d="${prism[1]}"/></svg>\`,
  spark: (sw, id) => \`<svg xmlns="http://www.w3.org/2000/svg" fill="none" viewBox="0 0 93 93" class="svg-animated-spark"><defs><linearGradient id="spark-beam-grad-\${id}" gradientUnits="userSpaceOnUse" x1="-30" y1="-30" x2="0" y2="0"><stop offset="0%" stop-color="var(--color-green-2)" stop-opacity="0"/><stop offset="50%" stop-color="var(--color-green-2)" stop-opacity="1"/><stop offset="100%" stop-color="var(--color-green-2)" stop-opacity="0"/></linearGradient></defs><g class="spark-static-group"><path data-from='{"rotation":30}' stroke="currentColor" stroke-width="\${sw}" d="${spark}"/></g><g><path d="${spark}" stroke="url(#spark-beam-grad-\${id})" fill="none" stroke-width="0.1"/></g></svg>\`,
};
`;
fs.writeFileSync('js/data/animated-icons.js', out);
console.log('ok', octagon.length, prism.length, spark.length);
